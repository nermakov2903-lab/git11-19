from logger import logger
from task3 import task3_menu
from task4 import task4_menu
from task8 import task8_menu

"""
Главный модуль программы.
Обеспечивает интерфейс верхнего уровня и доступ к отдельным заданиям.
"""

def main():
    """
    Запускает главное меню программы.

    Пользователь может выбрать одно из трёх заданий или завершить работу.

    Меню включает:
        1. Задание №3 — поворот матрицы на 90 градусов.
        2. Задание №4 — выполнение сложения и вычитания больших чисел,
           представленных массивами цифр.
        3. Задание №8 — поиск общих чисел двух массивов, включая реверсированные.
        4. Выход из программы.

    Notes
    -----
    Функция работает в цикле, пока пользователь явно не завершит программу.
    Взаимодействует с пользователем через консоль.
    Все действия пользователя логируются с помощью ``logger``.

    See Also
    --------
    task3_menu : Меню задания №3 (поворот матрицы).
    task4_menu : Меню задания №4 (арифметика больших чисел).
    task8_menu : Меню задания №8 (общие числа с реверсом).

    Examples
    --------
    >>> main()
    === ГЛАВНОЕ МЕНЮ ===
    1. Задание 3 (Поворот матрицы)
    2. Задание 4 (Операции над большими числами)
    3. Задание 8 (Общие числа с реверсом)
    4. Выход
    Выберите пункт: 1
    # ... дальнейшая работа программы
    """
    
    while True:
        print("\n=== ГЛАВНОЕ МЕНЮ ===")
        print("1. Задание 3 (Поворот матрицы)")
        print("2. Задание 4 (Операции над большими числами)")
        print("3. Задание 8 (Общие числа с реверсом)")
        print("4. Выход")

        choice = input("Выберите пункт: ")
        logger.info(f"Пользователь выбрал главный пункт меню: {choice}")

        if choice == "1":
            task3_menu()
        elif choice == "2":
            task4_menu()
        elif choice == "3":
            task8_menu()
        elif choice == "4":
            print("Выход...")
            break
        else:
            print("Неверный пункт!")
            logger.info("Ошибка: неверный пункт главного меню")


if __name__ == "__main__":
    main()
